"""Regenerate the keyword reference of the documentation site.

Writes the output of `robotcode doc lib` for both libraries to the reference page of their section
in docs/src/content/docs/. The pre-commit hook `keyword-reference` runs it. To run it by hand, from
the repository root:

    uv run python docs/scripts/generate_reference.py
"""

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOCS = ROOT / "docs" / "src" / "content" / "docs"
PAGES = [
    ("Electron", "electron", "Electron keyword reference"),
    ("VSCode", "vscode", "VS Code keyword reference"),
]
# The order puts the page after every other page of its section.
FRONTMATTER = """---
# Generated by docs/scripts/generate_reference.py from the keywords' docstrings. Do not edit.
title: {title}
description: Every keyword of the {library} library, including those that come from the Browser library.
sidebar:
  label: Keyword reference
  order: 100
---

"""


def main() -> int:
    with tempfile.TemporaryDirectory(prefix="reference-") as output:
        for library, section, title in PAGES:
            markdown = Path(output, f"{library}.md")
            command = ["robotcode", "-r", ".", "doc", "lib", "-o", str(markdown), library]
            if subprocess.run(command, cwd=ROOT, check=False).returncode != 0:
                print(f"`robotcode doc lib {library}` failed; its reference page was not updated.", file=sys.stderr)
                return 1
            # Starlight shows the title, and the library version before the introduction would go stale in a
            # committed page. The pre-commit hooks would remove the trailing whitespace anyway.
            text = markdown.read_text(encoding="utf-8")
            body = re.sub(r"[ \t]+$", "", text[text.index("## Introduction") :], flags=re.MULTILINE).rstrip()
            target = DOCS / section / "reference.md"
            target.write_text(FRONTMATTER.format(title=title, library=library) + body + "\n", encoding="utf-8")
            print(f"Updated {target.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
